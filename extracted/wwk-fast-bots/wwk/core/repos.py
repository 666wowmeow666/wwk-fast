"""Интерфейсы хранилищ. Реализации: memory_repo (тесты), db.repos (PostgreSQL)."""
from __future__ import annotations

from datetime import datetime
from typing import Protocol

from .models import AuditEntry, ClientBinding, Employee


class EmployeeRepo(Protocol):
    async def get_by_telegram_id(self, telegram_id: int) -> Employee | None: ...
    async def add(self, emp: Employee) -> Employee: ...
    async def save(self, emp: Employee) -> None: ...
    async def list_all(self) -> list[Employee]: ...
    async def count_active_admins(self) -> int: ...


class BindingRepo(Protocol):
    async def get(self, binding_id: int) -> ClientBinding | None: ...
    async def find(self, telegram_id: int, org_key: str) -> ClientBinding | None: ...
    async def list_for_telegram(self, telegram_id: int) -> list[ClientBinding]: ...
    async def list_pending(self) -> list[ClientBinding]: ...
    async def add(self, b: ClientBinding) -> ClientBinding: ...
    async def save(self, b: ClientBinding) -> None: ...


class AttemptRepo(Protocol):
    async def add_failure(self, key: str, at: datetime) -> None: ...
    async def count_since(self, key: str, since: datetime) -> int: ...
    async def clear(self, key: str) -> None: ...


class AuditRepo(Protocol):
    async def add(self, entry: AuditEntry) -> None: ...
    async def list_recent(self, limit: int = 20) -> list[AuditEntry]: ...
